/* One reusable frame buffer; callers draw it before requesting another frame. */
static uint8_t Kun_DanceBuffer[OLED_KUN_DANCE_BYTES];
static uint8_t Kun_DanceLastFrame;
static uint8_t Kun_DanceBufferValid;

static void Kun_ApplyFrameDelta(uint8_t FrameIndex)
{
    const uint8_t *source = Kun_DancePacked + Kun_DanceOffsets[FrameIndex];
    const uint8_t *end = Kun_DancePacked + Kun_DanceOffsets[FrameIndex + 1U];
    uint16_t position = 0;

    while (source < end)
    {
        uint8_t token = *source++;
        uint16_t length = (uint16_t)(token & 0x7FU) + 1U;
        uint16_t i;

        if (token & 0x80U)
        {
            for (i = 0; i < length; i++)
            {
                Kun_DanceBuffer[position++] ^= *source++;
            }
        }
        else
        {
            position += length;
        }
    }
}

const uint8_t *OLED_GetKunDanceFrame(uint8_t FrameIndex)
{
    uint8_t i;

    FrameIndex %= OLED_KUN_DANCE_FRAMES;
    if (Kun_DanceBufferValid && FrameIndex == Kun_DanceLastFrame)
    {
        return Kun_DanceBuffer;
    }

    if (Kun_DanceBufferValid && FrameIndex == Kun_DanceLastFrame + 1U)
    {
        Kun_ApplyFrameDelta(FrameIndex);
    }
    else
    {
        /* Rebuild from frame zero when entering, wrapping or seeking. */
        memset(Kun_DanceBuffer, 0, sizeof(Kun_DanceBuffer));
        for (i = 0; i <= FrameIndex; i++)
        {
            Kun_ApplyFrameDelta(i);
        }
    }

    Kun_DanceLastFrame = FrameIndex;
    Kun_DanceBufferValid = 1;
    return Kun_DanceBuffer;
}

